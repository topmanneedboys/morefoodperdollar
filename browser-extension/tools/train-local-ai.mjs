import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const repoRoot = path.resolve(root, '..');
const corpusPath = path.join(root, 'training', 'local_ai_corpus.json');
const jsPath = path.join(root, 'local-ai-model.js');
const androidPath = path.join(repoRoot, 'android', 'app', 'src', 'main', 'assets', 'local_ai_model.json');
const checkOnly = process.argv.includes('--check');

function tokenize(value) {
  const words = String(value ?? '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .match(/[a-z][a-z'-]{1,30}/g) || [];
  const stop = new Set(['and', 'with', 'the', 'for', 'from', 'style', 'fresh', 'classic', 'large', 'small', 'medium']);
  const clean = words.map(w => w.replace(/^'+|'+$/g, '')).filter(w => w.length > 1 && !stop.has(w));
  const features = new Set(clean.map(w => `u:${w}`));
  for (let i = 0; i + 1 < clean.length; i++) features.add(`b:${clean[i]}_${clean[i + 1]}`);
  return [...features];
}

const corpus = JSON.parse(fs.readFileSync(corpusPath, 'utf8'));
const classNames = Object.keys(corpus.classes).sort();
const vocabulary = new Set();
const tokenCounts = new Map();
let totalDocs = 0;

for (const name of classNames) {
  const examples = corpus.classes[name].examples;
  totalDocs += examples.length;
  const counts = new Map();
  let total = 0;
  for (const example of examples) {
    for (const token of tokenize(example)) {
      counts.set(token, (counts.get(token) || 0) + 1);
      vocabulary.add(token);
      total++;
    }
  }
  tokenCounts.set(name, { counts, total });
}

const alpha = 0.7;
const vocab = [...vocabulary].sort();
const output = {
  schemaVersion: 1,
  modelVersion: '101.0.0-local-nb1',
  algorithm: 'multinomial-naive-bayes-unigram-bigram',
  temperature: 1.35,
  vocabulary: vocab,
  classes: {}
};

const round = n => Number(n.toFixed(8));
for (const name of classNames) {
  const config = corpus.classes[name];
  const stats = tokenCounts.get(name);
  const denominator = stats.total + alpha * vocab.length;
  const tokenProbabilities = {};
  for (const [token, count] of [...stats.counts.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    tokenProbabilities[token] = round(Math.log((count + alpha) / denominator));
  }
  output.classes[name] = {
    label: config.label,
    food: config.food,
    portionEligible: config.portionEligible,
    basePortionPoints: config.basePortionPoints,
    meatRatio: config.meatRatio,
    logPrior: round(Math.log((config.examples.length + alpha) / (totalDocs + alpha * classNames.length))),
    unknownLogProbability: round(Math.log(alpha / denominator)),
    tokens: tokenProbabilities
  };
}

const json = `${JSON.stringify(output, null, 2)}\n`;
const js = `/* Generated by tools/train-local-ai.mjs. Do not edit by hand. */\n` +
  `(() => { const model = ${JSON.stringify(output)}; ` +
  `if (typeof module !== 'undefined' && module.exports) module.exports = model; ` +
  `globalThis.ValuePilotLocalAIModel = model; })();\n`;

function verifyOrWrite(filePath, value) {
  if (checkOnly) {
    const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : '';
    if (current !== value) throw new Error(`Generated model is stale: ${path.relative(repoRoot, filePath)}`);
    return;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, value);
}

verifyOrWrite(jsPath, js);
verifyOrWrite(androidPath, json);
console.log(checkOnly ? 'Local AI model outputs are current.' : `Generated ${vocab.length} local AI features.`);
